// Builds the Apps Script file you paste into the sheet (dist/Code.gs), the page GitHub Pages
// serves (docs/index.html), local previews that run the same server code against a fake
// spreadsheet (preview/index.html via google.script.run, preview/fetch.html via the web API),
// and PLAN.md.
// Usage: node build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const at = (p) => new URL(p, import.meta.url);
const read = (p) => readFileSync(at(p), 'utf8');

const html = read('src/Index.html');
const code = [
  '// Challenge 2026 tracker. Paste this whole file into Extensions > Apps Script, replacing Code.gs.',
  '// Generated by build.mjs from src/. Edit the sources and rebuild rather than editing this file.',
  '',
  read('src/Server.gs'),
  read('src/Seed.gs'),
].join('\n');

mkdirSync(at('dist/'), { recursive: true });
writeFileSync(at('dist/Code.gs'), code);

mkdirSync(at('docs/'), { recursive: true });
writeFileSync(at('docs/index.html'), html);

// Everything inlined, so the previews also work where a page can't load sibling files.
mkdirSync(at('preview/'), { recursive: true });
if (!html.includes('<head>')) throw new Error('Index.html needs a plain <head> tag for the preview');
const inline = (js) => '<script>\n' + js.replace(/<\/script/gi, '<\\/script') + '\n</script>';
const preview = (pre) => html.replace('<head>', () => '<head>\n' + pre + inline(read('src/preview-shim.js')) + '\n' + inline(code));
writeFileSync(at('preview/index.html'), preview(''));
writeFileSync(at('preview/fetch.html'), preview(inline('window.__PREVIEW_FETCH = true;') + '\n'));

// PLAN.md: a readable copy of the seeded plan.
const seed = new Function(code + '\nreturn { PLAN_WEEKS_, GOALS_, ROUTINE_, addDays_ };')();
const lines = ['# Challenge 2026: the plan', '',
  'Generated from the tracker seed. The live version (with your progress) is the Roadmap in the app and the Plan tab in the sheet.', '',
  '## Daily shape', ''];
for (const type of ['Weekday', 'Saturday', 'Sunday']) {
  const rows = seed.ROUTINE_.filter((r) => r[0] === type);
  const total = rows.reduce((s, r) => s + (Number(r[4]) || 0), 0);
  lines.push(`### ${type} (about ${total}h)`, '');
  rows.forEach((r) => lines.push(r[2] === 'Tip' ? `> ${r[3]}` : `- **${r[2]}** (${r[4]}h): ${r[3]}`));
  lines.push('');
}
lines.push('## Monthly goals', '');
let month = '';
for (const [m, area, goal] of seed.GOALS_) {
  if (m !== month) { lines.push('', `### ${m}`, ''); month = m; }
  lines.push(`- **${area}**: ${goal}`);
}
lines.push('', '## Week by week', '');
for (const w of seed.PLAN_WEEKS_) {
  const end = w.end || seed.addDays_(w.start, 6);
  lines.push(`### ${w.week}: ${w.start} to ${end}`, '');
  w.tasks.forEach(([track, task, details]) => lines.push(`- **${track}**: ${task}${details ? `. ${details}` : ''}`));
  lines.push('');
}
writeFileSync(at('PLAN.md'), lines.join('\n'));

console.log(`dist/Code.gs ${(code.length / 1024).toFixed(1)} KB, preview/ and PLAN.md written`);
